"""
Axis C -- Regime Modeling: strictly-causal Gaussian Hidden Markov Model (HMM) regime gate.

Replaces the binary 200-day-SMA trend filter used elsewhere in this program with a SMOOTH,
forward-filtered posterior probability of a "bull" state, directly addressing Established Fact
(4): trailing realized volatility is reactive and missed the 2025-04-09-style sudden reversal
(realized vol was an unremarkable ~2% that very morning). An HMM instead tracks the LEVEL AND
VARIANCE of returns jointly through a latent discrete state and can, in principle, place
meaningful posterior mass on a "stressed" state before a trailing vol window has accumulated
enough large moves to react.

--------------------------------------------------------------------------------------------
CAUSALITY CONTRACT (read this before calling anything below)
--------------------------------------------------------------------------------------------
Every public function that returns a per-day exposure-scaling signal returns, at row t, a value
computed using ONLY returns through t-1 -- both in terms of (a) which observations were used to
FIT the model's parameters (a refit's training window always ends strictly before the first day
its parameters are applied to) and (b) which observations were used to FILTER the model's state
forward to produce day t's regime probability (the forward algorithm, not forward-backward
smoothing). This is proven empirically by `injection_test()` in this module: a large synthetic
price shock injected at index i must leave every predictive value at index <= i BIT-IDENTICAL to
the unshocked run, and must first appear at index i+1, never at index i itself. A deliberately
WRONG "naive" control (`_naive_same_day_pbull`) is included and is proven to react at index i
itself (same day) -- this demonstrates the injection test has real discriminating power and is
not a tautology that would pass trivially.

hmmlearn (tested against hmmlearn==0.3.3) is used ONLY for the EM (Baum-Welch) parameter-fitting
step (`GaussianHMM.fit`) on an already-causal, frozen training window. Posterior probabilities
used as trading signals are NEVER taken from hmmlearn's own `.predict_proba` / `.score_samples` --
those implement smoothing (forward-BACKWARD over the entire array passed in) and would silently
leak future information if called on anything but a training window whose last row is the most
recent point anyone is allowed to know about. Investigation note: hmmlearn's smoothed posterior
at the LAST row of an array does mathematically coincide with the pure forward-filtered posterior
(because the backward variable at the terminal step is identically 1), so it would be possible in
principle to call `predict_proba` on a repeatedly-truncated growing prefix and read off only the
last row -- but that pattern is (a) O(T^2) if done naively per day, (b) fragile to depend on
should hmmlearn's internal smoothing implementation ever change, and (c) far less legible to an
independent verifier than an explicit from-scratch forward recursion. This module therefore
implements the forward algorithm directly (`_forward_filter`) and uses hmmlearn purely as an EM
optimizer for (mu_k, sigma_k^2, transition matrix, initial distribution) on data it is never fed
future information within.

--------------------------------------------------------------------------------------------
MODEL
--------------------------------------------------------------------------------------------
Daily log return r_t is generated by a first-order Markov chain of hidden states S_t in {1..K}
with transition matrix A (A[i,j] = P(S_t=j | S_{t-1}=i)) and, conditional on S_t=k, a Gaussian
emission r_t | S_t=k ~ N(mu_k, sigma_k^2), independent across t given the state path (Hamilton
1989's regime-switching framework, here with an i.i.d.-conditional-on-state Gaussian emission
rather than an autoregressive one -- see markdown for the tradeoff discussion).

States are labeled ex-post by sorted fitted mean: the "bull" state is the state with the HIGHEST
fitted mean (mu), the "bear" state has the LOWEST fitted mean. For n_states==2 there is no
separate neutral state (p_bear = 1 - p_bull exactly). For n_states==3, the middle-mean state is
reported but not specially labeled (an integration agent may treat it as "neutral"/"chop").
"""

from __future__ import annotations

import warnings
from dataclasses import dataclass

import numpy as np
import pandas as pd

from hmmlearn.hmm import GaussianHMM

_MIN_VAR = 1e-10
_LOG2PI = np.log(2.0 * np.pi)


# ==================================================================================================
# Low-level: Gaussian emission + pure forward algorithm (filtering, never smoothing)
# ==================================================================================================
def _gauss_pdf_vec(x: float, means: np.ndarray, vars_: np.ndarray) -> np.ndarray:
    v = np.maximum(vars_, _MIN_VAR)
    return np.exp(-0.5 * (x - means) ** 2 / v) / np.sqrt(2.0 * np.pi * v)


def _forward_filter(
    returns: np.ndarray, startprob: np.ndarray, transmat: np.ndarray,
    means: np.ndarray, vars_: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Pure forward algorithm over a 1-D return array. NEVER looks at returns[t] to produce
    predictive[t] -- only returns[0..t-1] and the fixed (means, vars_, transmat) params.

    Returns
    -------
    predictive : (T, K) array. predictive[t, k] = P(S_t=k | r_0..r_{t-1}, theta), i.e. the
        one-step-ahead forecast BEFORE observing r_t. THIS is the array to use for sizing day t's
        exposure. predictive[0] = startprob (the state belief handed in, computed from whatever
        history preceded this array -- see `causal_hmm_regime_posterior`).
    filtered : (T, K) array. filtered[t, k] = P(S_t=k | r_0..r_t, theta), i.e. the posterior AFTER
        observing r_t. This seeds the next day's (or next segment's) prediction. NEVER use
        filtered[t] to size day t's own exposure -- that is exactly the off-by-one lookahead bug
        `_naive_same_day_pbull` deliberately reproduces as a control.
    """
    T = len(returns)
    K = len(startprob)
    predictive = np.zeros((T, K))
    filtered = np.zeros((T, K))
    prev_filtered = np.asarray(startprob, dtype=float).copy()
    for t in range(T):
        pred = prev_filtered @ transmat
        pred = pred / pred.sum() if pred.sum() > 0 else np.full(K, 1.0 / K)
        predictive[t] = pred
        b = _gauss_pdf_vec(returns[t], means, vars_)
        unnorm = pred * b
        s = unnorm.sum()
        if not np.isfinite(s) or s <= 0:
            filt = pred.copy()  # degenerate emission likelihood (extreme outlier): fall back to
                                 # the predictive belief rather than emit NaN/inf downstream.
        else:
            filt = unnorm / s
        filtered[t] = filt
        prev_filtered = filt
    return predictive, filtered


# ==================================================================================================
# EM parameter fitting (hmmlearn, used ONLY on a frozen, already-causal training window)
# ==================================================================================================
@dataclass
class HMMParams:
    n_states: int
    startprob: np.ndarray
    transmat: np.ndarray
    means: np.ndarray
    vars_: np.ndarray
    bull_state: int
    bear_state: int
    train_n_obs: int
    log_likelihood: float


def fit_hmm_on_window(
    train_returns: np.ndarray, n_states: int, n_restarts: int = 5, random_state: int = 0,
) -> HMMParams:
    """Fit a Gaussian HMM by EM (Baum-Welch, via hmmlearn) on `train_returns` ONLY -- the caller
    is responsible for ensuring this array contains no observation at or after the first day the
    resulting params will be applied to (this function has no notion of dates/causality itself;
    it is a pure numerical fit on whatever array it is handed).

    Multiple random restarts (`n_restarts`) are run and the highest-log-likelihood fit is kept,
    because EM on a mixture/HMM is only guaranteed to reach a LOCAL optimum and Gaussian HMMs are
    well known to be sensitive to initialization (label-switching + local optima both cataloged in
    the HMM literature, e.g. Bishop 2006 ch.13.2; Cappe/Moulines/Ryden 2005 ch.1).
    """
    if len(train_returns) < max(30, 5 * n_states):
        raise ValueError(f"train window too short ({len(train_returns)} obs) for {n_states}-state HMM")
    X = np.asarray(train_returns, dtype=float).reshape(-1, 1)
    best = None
    best_ll = -np.inf
    for i in range(n_restarts):
        seed = int(random_state) * 100003 + i * 7919 + 3
        model = GaussianHMM(
            n_components=n_states, covariance_type="diag", n_iter=200, tol=1e-4,
            random_state=seed, init_params="stmc", params="stmc",
        )
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                model.fit(X)
                ll = model.score(X)
        except Exception:
            continue
        if np.isfinite(ll) and ll > best_ll:
            best_ll = ll
            best = model
    if best is None:
        raise RuntimeError(f"HMM EM fit failed to converge for all {n_restarts} restarts")

    means = best.means_.ravel().astype(float)
    vars_ = np.maximum(best.covars_.reshape(n_states, -1)[:, 0].astype(float), _MIN_VAR)
    transmat = best.transmat_.astype(float)
    startprob = best.startprob_.astype(float)
    order = np.argsort(means)
    return HMMParams(
        n_states=n_states, startprob=startprob, transmat=transmat, means=means, vars_=vars_,
        bull_state=int(order[-1]), bear_state=int(order[0]),
        train_n_obs=len(train_returns), log_likelihood=float(best_ll),
    )


# ==================================================================================================
# Main causal driver
# ==================================================================================================
def causal_hmm_regime_posterior(
    returns: pd.Series,
    n_states: int = 2,
    refit_every: int = 63,
    min_train: int = 252,
    window_type: str = "expanding",
    rolling_window: int = 1260,
    n_restarts: int = 5,
    random_state: int = 0,
) -> pd.DataFrame:
    """Strictly-causal smooth regime posterior, meant as a drop-in replacement for a binary
    200-day-SMA trend filter: exposure_scale[t] = p_bull[t] (optionally floored/capped via
    `exposure_scale_from_posterior`) rather than exposure_scale[t] in {0, 1}.

    Parameters
    ----------
    returns : pd.Series of daily log (or simple -- either is fine, just be consistent) returns,
        DatetimeIndex, ALREADY filtered to source=='duka' upstream and built via
        daily_close_series_duka + .diff/.pct_change (this function does not touch price levels or
        the source column itself -- that discipline is the caller's responsibility, matching
        bug-pattern 1 in the house conventions).
    n_states : 2 or 3.
    refit_every : re-estimate (mu_k, sigma_k^2, A) by EM every `refit_every` TRADING days.
    min_train : minimum real observations required before the first fit; rows before this index
        are NaN (point-in-time gate, exactly parallel to sma200 requiring 200 real prior days).
    window_type : "expanding" (default, training window = returns[0:anchor], grows every refit)
        or "rolling" (training window = returns[anchor-rolling_window:anchor], fixed width).
    rolling_window : width used only when window_type=="rolling".
    n_restarts, random_state : passed through to `fit_hmm_on_window`.

    Returns
    -------
    pd.DataFrame indexed like `returns.index`, columns:
      p_state_0 .. p_state_{K-1}  predictive P(S_t=k | r_0..r_{t-1}); NaN before min_train.
      p_bull                       predictive P(S_t = bull-labeled state | ...).
      p_bear                       predictive P(S_t = bear-labeled state | ...).
      state_argmax                 argmax of predictive dist (diagnostic only; do not use as the
                                    actual sizing signal -- use p_bull directly, it is smooth by
                                    construction).
      refit_date                   calendar date of the most recent refit's training-window end
                                    (last date INCLUDED in that fit); NaT before the first refit.
    """
    if window_type not in ("expanding", "rolling"):
        raise ValueError("window_type must be 'expanding' or 'rolling'")
    r = returns.astype(float)
    idx = r.index
    T = len(r)
    vals = r.to_numpy()

    cols_state = [f"p_state_{k}" for k in range(n_states)]
    out = pd.DataFrame(
        np.nan, index=idx, columns=cols_state + ["p_bull", "p_bear", "state_argmax"],
    )
    # dtype must match idx's own tz-awareness (or lack thereof) -- a naive datetime64[ns] Series
    # cannot hold a tz-aware Timestamp assignment (raises TypeError), so infer the dtype from idx.
    refit_dtype = idx.dtype if isinstance(idx, pd.DatetimeIndex) else "datetime64[ns]"
    refit_date = pd.Series(pd.NaT, index=idx, dtype=refit_dtype)

    if T <= min_train:
        return pd.concat([out, refit_date.rename("refit_date")], axis=1)

    anchors = list(range(min_train, T, refit_every))
    for seg_i, a in enumerate(anchors):
        b = anchors[seg_i + 1] if seg_i + 1 < len(anchors) else T
        train_start = 0 if window_type == "expanding" else max(0, a - rolling_window)
        train_window = vals[train_start:a]
        params = fit_hmm_on_window(
            train_window, n_states=n_states, n_restarts=n_restarts, random_state=random_state,
        )
        # Fresh causal forward pass over the TRAINING window itself (using the just-fit params)
        # to obtain filtered_{a-1}: the state belief as of the end of the training window. This
        # is legitimate information (entirely history through a-1) and seeds the live segment.
        _, filt_train = _forward_filter(
            train_window, params.startprob, params.transmat, params.means, params.vars_,
        )
        seed = filt_train[-1]
        live_returns = vals[a:b]
        pred_seg, _ = _forward_filter(
            live_returns, seed, params.transmat, params.means, params.vars_,
        )
        out.iloc[a:b, out.columns.get_indexer(cols_state)] = pred_seg
        out.iloc[a:b, out.columns.get_loc("p_bull")] = pred_seg[:, params.bull_state]
        out.iloc[a:b, out.columns.get_loc("p_bear")] = pred_seg[:, params.bear_state]
        out.iloc[a:b, out.columns.get_loc("state_argmax")] = pred_seg.argmax(axis=1)
        refit_date.iloc[a:b] = idx[a - 1]

    return pd.concat([out, refit_date.rename("refit_date")], axis=1)


def _naive_same_day_pbull(
    returns: pd.Series, n_states: int = 2, refit_every: int = 63, min_train: int = 252,
    window_type: str = "expanding", rolling_window: int = 1260, n_restarts: int = 5,
    random_state: int = 0,
) -> np.ndarray:
    """DELIBERATELY WRONG control, used only by `injection_test()`. Identical to
    `causal_hmm_regime_posterior` except it reads off `filtered` (posterior AFTER observing r_t,
    i.e. P(S_t | r_0..r_t)) and mislabels it as day t's signal -- the exact same-day-lookahead bug
    pattern as i1_pipeline.py's `canary=True` path for the 200-day-SMA filter. This function must
    NEVER be used to size a real trading exposure; it exists solely to prove `injection_test`
    below has discriminating power (a test that both the causal and a genuinely-broken
    implementation pass would be a tautology)."""
    r = returns.astype(float)
    vals = r.to_numpy()
    T = len(r)
    out = np.full(T, np.nan)
    if T <= min_train:
        return out
    anchors = list(range(min_train, T, refit_every))
    for seg_i, a in enumerate(anchors):
        b = anchors[seg_i + 1] if seg_i + 1 < len(anchors) else T
        train_start = 0 if window_type == "expanding" else max(0, a - rolling_window)
        train_window = vals[train_start:a]
        params = fit_hmm_on_window(train_window, n_states=n_states, n_restarts=n_restarts, random_state=random_state)
        _, filt_train = _forward_filter(train_window, params.startprob, params.transmat, params.means, params.vars_)
        seed = filt_train[-1]
        live_returns = vals[a:b]
        _, filt_seg = _forward_filter(live_returns, seed, params.transmat, params.means, params.vars_)
        out[a:b] = filt_seg[:, params.bull_state]  # BUG: same-day filtered, not t-1 predictive
    return out


def injection_test(
    returns: pd.Series, injection_idx: int | None = None, shock: float = 0.5, **kwargs,
) -> dict:
    """Synthetic-outlier-injection causality proof, per the program's Independent Verify
    discipline. Injects a large fake return shock at `injection_idx` (default: 10 trading days
    before the end of the series, deliberately inside the final refit segment so params fit on
    data through the most recent refit anchor are bit-identical between the base and shocked runs
    -- isolating the day-by-day forward-filter propagation as the only possible source of any
    divergence) and checks:
      1. `causal_hmm_regime_posterior`'s p_bull is IDENTICAL between the base and shocked run for
         every index <= injection_idx (nothing at or before the shock can possibly change), and
         FIRST diverges at exactly injection_idx + 1 (the first day whose predictive distribution
         is conditioned on r_0..r_{injection_idx}, which now includes the shock).
      2. `_naive_same_day_pbull` (the deliberately-wrong same-day control) diverges AT
         injection_idx itself -- proving the test has real discriminating power, not just a
         tautology that any implementation would pass.
    """
    n = len(returns)
    if injection_idx is None:
        injection_idx = n - 10
    if not (0 <= injection_idx < n - 1):
        raise ValueError("injection_idx must leave room for at least one post-shock observation")

    base = returns.copy()
    shocked = returns.copy()
    shocked.iloc[injection_idx] = shocked.iloc[injection_idx] + shock

    causal_base = causal_hmm_regime_posterior(base, **kwargs)["p_bull"].to_numpy()
    causal_shock = causal_hmm_regime_posterior(shocked, **kwargs)["p_bull"].to_numpy()
    naive_base = _naive_same_day_pbull(base, **kwargs)
    naive_shock = _naive_same_day_pbull(shocked, **kwargs)

    diff_causal = np.abs(causal_base - causal_shock)
    diff_naive = np.abs(naive_base - naive_shock)
    tol = 1e-9

    def first_divergence(diff: np.ndarray) -> int | None:
        for i, d in enumerate(diff):
            if np.isfinite(d) and d > tol:
                return i
        return None

    causal_first = first_divergence(diff_causal)
    naive_first = first_divergence(diff_naive)
    max_before = diff_causal[: injection_idx + 1]
    max_before = float(np.nanmax(max_before)) if len(max_before) else 0.0

    return {
        "injection_idx": int(injection_idx),
        "n_obs": int(n),
        "shock": float(shock),
        "causal_first_divergence_idx": causal_first,
        "naive_first_divergence_idx": naive_first,
        "causal_passes": causal_first == injection_idx + 1,
        "naive_reacts_same_day": naive_first == injection_idx,
        "max_abs_diff_at_or_before_injection_causal": max_before,
        "PASS": (causal_first == injection_idx + 1) and (naive_first == injection_idx) and (max_before == 0.0),
    }


# ==================================================================================================
# Explicit null / baseline: 200-day SMA binary gate (same causality convention, for comparison)
# ==================================================================================================
def sma_binary_gate(close: pd.Series, window: int = 200, band: float = 0.02) -> pd.Series:
    """Binary trend-filter NULL/BASELINE for Axis C's comparison. Reimplements, self-contained
    (not imported from main), the established convention used elsewhere in this program
    (research/indices/i1_pipeline.py's `s1_sma_band_state`): 200-day SMA +/-`band` hysteresis,
    decide-at-close/act-next-day. state[t] in {0.0, 1.0} uses close[t-1] and sma[t-1] ONLY --
    identical causality convention to the HMM functions above, so the two are directly comparable
    apples-to-apples as exposure-scaling signals in the Sweep phase.
    """
    sma = close.rolling(window, min_periods=window).mean()
    px_ref = close.shift(1).to_numpy()
    upper = (sma.shift(1) * (1 + band)).to_numpy()
    lower = (sma.shift(1) * (1 - band)).to_numpy()
    n = len(close)
    out = np.full(n, np.nan)
    prev = 0.0
    for i in range(n):
        p, u, lo = px_ref[i], upper[i], lower[i]
        if np.isnan(u) or np.isnan(lo):
            continue
        if p > u:
            prev = 1.0
        elif p < lo:
            prev = 0.0
        out[i] = prev
    return pd.Series(out, index=close.index, name="sma_gate")


# ==================================================================================================
# Convenience: turning either signal into a usable exposure scale
# ==================================================================================================
def exposure_scale_from_posterior(p_bull: pd.Series, floor: float = 0.0, cap: float = 1.0) -> pd.Series:
    """Clip p_bull into [floor, cap]. With defaults this is the identity (p_bull is already in
    [0,1]); floor/cap are exposed for a later Sweep-phase grid that may want e.g. a floor > 0 to
    avoid ever going fully flat, or a cap < 1 as a risk budget."""
    return p_bull.clip(lower=floor, upper=cap)
